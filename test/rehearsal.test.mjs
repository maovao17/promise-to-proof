import test from 'node:test';
import assert from 'node:assert/strict';
import {spawnSync} from 'node:child_process';
import {mkdtempSync,writeFileSync,readFileSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {CaseStore} from '../src/store.mjs';
import {act,brief} from '../src/runtime.mjs';
import {BookingStore} from '../src/bookings.mjs';
test('OFFLINE integration: decision, restart, failed review, changed scope, stale rejection, verified reply',t=>{
 const dir=mkdtempSync(join(tmpdir(),'p2p-rehearsal-'));t.after(()=>rmSync(dir,{recursive:true,force:true}));
 const db=join(dir,'cases.sqlite');let s=new CaseStore(db);t.after(()=>s.close());
 s.create('DEMO','Synthetic prospect needs spreadsheet migration');
 const send=(role,e)=>act(s,role,'DEMO',e);
 send('coordinator',{id:'s1',type:'scope',expectedVersion:0,scope:'Spreadsheet import',criteria:['Preview']});
 send('founder',{id:'a1',type:'approve',version:1,approvalRef:'SIMULATED founder decision'});
 send('builder',{id:'b1',type:'start',version:1});
 send('builder',{id:'p1',type:'submit',version:1,commit:'fixture-commit-v1'});
 send('reviewer',{id:'v1',type:'verify',version:1,commit:'fixture-commit-v1',passed:false,evidenceRef:'SIMULATED failing fixture'});
 assert.equal(s.get('DEMO').status,'building');
 send('coordinator',{id:'s2',type:'scope',expectedVersion:1,scope:'CSV only, preview and explicit save',criteria:['Preview is pure','Invalid rows block save','No duplicate bookings']});
 assert.equal(s.get('DEMO').approval,null);
 assert.throws(()=>send('builder',{id:'stale',type:'submit',version:1,commit:'old'}),/Stale/);
 send('founder',{id:'a2',type:'approve',version:2,approvalRef:'SIMULATED revised decision'});
 s.close();s=new CaseStore(db);
 assert.equal(brief(s,'builder','DEMO').case.version,2);
 send('builder',{id:'b2',type:'start',version:2});
 const csv=readFileSync(new URL('../fixtures/bookings-valid.csv',import.meta.url),'utf8');
 const bookings=new BookingStore(join(dir,'bookings.sqlite'));
 assert.equal(bookings.preview(csv).valid.length,2);assert.equal(bookings.list().length,0);
 assert.equal(bookings.commit(csv).saved,2);assert.equal(bookings.commit(csv).saved,0);bookings.close();
 send('builder',{id:'p2',type:'submit',version:2,commit:'fixture-commit-v2'});
 send('reviewer',{id:'v2',type:'verify',version:2,commit:'fixture-commit-v2',passed:true,evidenceRef:'OFFLINE actual importer assertions'});
 send('coordinator',{id:'d2',type:'draft',version:2,text:'CSV import is ready for review; Excel is outside this scope.'});
 assert.equal(brief(s,'founder','DEMO').nextOwner,'founder');
 send('founder',{id:'r2',type:'release',version:2,releaseRef:'SIMULATED demo release',approvalRef:'SIMULATED founder'});
 send('founder',{id:'n2',type:'notify',version:2,approvedText:s.get('DEMO').draft.text,receipt:'SIMULATED no email sent',approvalRef:'SIMULATED founder'});
 send('coordinator',{id:'c2',type:'confirm',version:2,customerEvidence:'SIMULATED customer confirmation'});
 assert.equal(s.get('DEMO').status,'confirmed');
 // Reopen via an actual separate CLI process.
 const child=spawnSync(process.execPath,['scripts/case.mjs','brief','reviewer','DEMO'],{cwd:new URL('../',import.meta.url),env:{...process.env,P2P_DB:db},encoding:'utf8'});
 assert.equal(child.status,0,child.stderr);assert.equal(JSON.parse(child.stdout).case.status,'confirmed');
 console.log('OFFLINE REHEARSAL passed; real Switch conversation and external delivery are separate.');
});
